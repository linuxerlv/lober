package authoring

import "context"

// Bootstrapper 属于编写应用，仅允许受信任的程序启动入口在身份初始化前调用；
// 不接收网页身份、操作者或运行时用户输入，因此不做用户权限判定。
type Bootstrapper interface {
	// Initialise 按构造时的清单顺序先装载全部组件，再装载全部模板。
	// 输入仅为必传的启动上下文；发布对象由组装点按内置发布格式提供，应用不读文件、
	// 不规范化或另设批量大小限制，单对象必填项、名字及可存文本由仓储契约检查。
	// 无返回数据；空清单不写入并返回 nil。遇到首个失败对象即停止，不处理后续对象。
	// 每次存储调用前先检查取消或截止时间；之后原样返回存储错误。只有 errors.Is
	// 匹配 repository.ErrConflict 才重试同一对象，最多四次；第四次冲突原样返回。
	// ErrInvalid、ErrBuiltinMismatch、DuplicateError 及其他错误均不重试、不转换；
	// 没有额外业务原因代码。成功写入后不追加取消检查，也不撤回已完成的写入。
	// 重复调用从清单开头重新装载；相同 ID、版本和内容由仓储保证幂等，内容不同报错。
	// 原子边界是单个对象及其身份、版本和引用，整份清单没有共同事务；早先成功保留。
	// 并发时仓储在事务内锁住最新身份、复查名字与版本内容，并依赖唯一约束处理竞争；
	// 应用不缓存这些事实。没有用户审计或通知，截止时间随原上下文传给仓储。
	Initialise(context.Context) error
}

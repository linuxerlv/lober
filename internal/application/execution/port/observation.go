// Package port 声明执行模块需要的最小外部能力。
package port

// IPObservationSink 接收执行模块已计算好的机器地址归属；仅供可信机器流量观察调用。
// 输入按任务编号、原尝试号、原连接地址、到期秒顺序传入，不在本接口规范化或增加大小限制。
// 无返回值、空结果或错误代码；实现自行拒绝不合适地址和过期登记。
// 只更新临时地址归属，不写任务、事件或审计，没有跨数据事务。
// 重复登记覆盖原归属；无重试或版本冲突协议，实现自行保护并发登记和读取。
// 到期判定由实现读取自身时钟；不要求提交复查，不承诺登记必定保留。
// 无审计、通知、上下文或超时；同步调用，调用方仅在原凭据检查成功的位置使用。
type IPObservationSink interface {
	ObserveIP(string, int, string, int64)
}

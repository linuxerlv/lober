// Package ports 定义多个应用流程共用的外部能力。
package ports

// Notifier 只提示某任务可能有新事件，多次提示可以合并。
// 消费者收到提示后重新读取已提交事件；不能把提示当作完整事件记录。
// Publish 必须在业务事务成功提交后调用；失败或取消时不发布。
// Subscribe 返回容量为一的提示通道与可重复调用的退订函数。
// 退订会关闭通道，并且可以和发布并发调用。
type Notifier interface {
	// Publish 供可信提交方按原任务编号发提示，不校验或规范化编号；没有返回值或错误。
	// 只改内存提示，不保存事件、审计或事务；重复提示可合并，无版本冲突、提交复查、上下文或超时。
	Publish(string)
	// Subscribe 供可信消费者订阅原任务编号，返回容量一的通道和退订函数，无错误。
	// 不重放历史、不持久化、不写审计；重复订阅各自独立，退订可重复并与发布并发。
	// 无数据库提交复查、版本冲突或取消上下文，调用方断开时必须退订。
	Subscribe(string) (<-chan struct{}, func())
}

package ports

// SelectionGuard 协调同一进程内的选择与模板状态变更。
// 等待锁不能立即取消；取得锁后继续传递取消状态。数据库事务仍负责跨实例保护。
type SelectionGuard interface {
	// ReadLock 供可信向导取得共享选择保护，无输入或错误，返回必须调用一次的释放函数。
	// 只改进程内锁，不写记录、审计或通知；可并发读，无版本冲突重试或数据库提交保证，不接收上下文。
	ReadLock() func()
	// WriteLock 供可信模板审批/废弃排他保护，无输入或错误，返回必须调用一次的释放函数。
	// 等待已有读写锁释放；只改进程内锁，无业务事务、审计、通知或上下文，不代替仓储最新事实复查。
	WriteLock() func()
}

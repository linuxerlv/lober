import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const target = new URL(
  '../apps/web-ele/src/api/console/generated.ts',
  import.meta.url,
);
const doc = JSON.parse(
  execFileSync(process.env.GO || 'go', ['run', './cmd/console-openapi'], {
    cwd: root,
    encoding: 'utf8',
  }),
);
const quote = JSON.stringify;
function type(s = {}) {
  let result;
  if (s.$ref) result = `Schemas[${quote(s.$ref.split('/').at(-1))}]`;
  else if (s.enum) result = s.enum.map(quote).join(' | ') || 'never';
  else if (s.oneOf || s.anyOf)
    result = (s.oneOf || s.anyOf).map(type).join(' | ');
  else if (s.allOf) result = s.allOf.map(type).join(' & ');
  else if (s.type === 'array') result = `Array<${type(s.items)}>`;
  else if (s.type === 'integer' || s.type === 'number') result = 'number';
  else if (s.type === 'string')
    result = s.format === 'binary' ? 'Blob' : 'string';
  else if (s.type === 'boolean') result = 'boolean';
  else if (s.type === 'object' || s.properties) {
    const props = Object.entries(s.properties || {})
      .sort(([a], [b]) => a.localeCompare(b, 'en'))
      .map(
        ([k, v]) =>
          `${quote(k)}${s.required?.includes(k) ? '' : '?'}: ${type(v)};`,
      );
    if (s.additionalProperties)
      props.push(
        `[key: string]: ${s.additionalProperties === true ? 'unknown' : type(s.additionalProperties)};`,
      );
    result = props.length
      ? `{ ${props.join(' ')} }`
      : 'Record<string, unknown>';
  } else result = 'unknown';
  return s.nullable && !s.enum?.includes(null) ? `(${result}) | null` : result;
}
function content(c) {
  return `{ ${Object.entries(c || {})
    .map(([media, value]) => `${quote(media)}: ${type(value.schema)};`)
    .join(' ')} }`;
}
const lines = [
  '/* eslint-disable */',
  '/* Generated by scripts/generate-console-types.mjs from console.OpenAPI(). Do not edit. */',
  '// prettier-ignore',
  'export interface Schemas {',
];
for (const [name, schema] of Object.entries(doc.components.schemas).sort(
  ([a], [b]) => a.localeCompare(b, 'en'),
))
  lines.push(`  ${quote(name)}: ${type(schema)};`);
lines.push('}', '', '// prettier-ignore', 'export interface Paths {');
for (const [path, methods] of Object.entries(doc.paths).sort(([a], [b]) =>
  a.localeCompare(b, 'en'),
)) {
  lines.push(`  ${quote(path)}: {`);
  for (const [method, op] of Object.entries(methods).sort(([a], [b]) =>
    a.localeCompare(b, 'en'),
  )) {
    lines.push(`    ${quote(method)}: {`);
    for (const location of ['path', 'query', 'header']) {
      const params = op.parameters?.filter((p) => p.in === location);
      if (params?.length)
        lines.push(
          `      ${location}: { ${params.map((p) => `${quote(p.name)}${p.required ? '' : '?'}: ${type(p.schema)};`).join(' ')} };`,
        );
    }
    if (op.requestBody)
      lines.push(`      requestBody: ${content(op.requestBody.content)};`);
    lines.push(
      `      responses: { ${Object.entries(op.responses)
        .map(
          ([status, response]) =>
            `${quote(status)}: ${content(response.content)};`,
        )
        .join(' ')} };`,
      '    };',
    );
  }
  lines.push('  };');
}
lines.push('}', '');
const output = lines.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Console types drifted. Run the generator.');
    process.exitCode = 1;
  }
} else writeFileSync(target, output);
